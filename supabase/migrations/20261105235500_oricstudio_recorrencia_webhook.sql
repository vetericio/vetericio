-- Etapa 4/5 - checkout mensal OricStúdio, isolado das assinaturas do ORICSE.
-- Nenhuma contratação é ativada ao abrir checkout ou ao retornar do navegador.
alter table public.oricstudio_solicitacoes
  add column if not exists mp_assinatura_id text,
  add column if not exists mp_assinatura_status text,
  add column if not exists ultimo_erro_checkout text;
create unique index if not exists oricstudio_solicitacoes_mp_assinatura_unica
  on public.oricstudio_solicitacoes(mp_assinatura_id)
  where mp_assinatura_id is not null;

create table if not exists public.oricstudio_pagamentos (
  id bigint generated by default as identity primary key,
  solicitacao_id uuid not null references public.oricstudio_solicitacoes(id) on delete cascade,
  clinica_id uuid not null references public.clinicas(id) on delete cascade,
  mp_pagamento_id text not null unique,
  mp_assinatura_id text not null,
  valor_centavos integer not null check (valor_centavos > 0),
  aprovado_em timestamptz not null,
  registrado_em timestamptz not null default now()
);
create index if not exists oricstudio_pagamentos_clinica_idx on public.oricstudio_pagamentos(clinica_id, aprovado_em desc);
alter table public.oricstudio_pagamentos enable row level security;
revoke all on public.oricstudio_pagamentos from public,anon,authenticated;
grant select on public.oricstudio_pagamentos to authenticated;
create policy oricstudio_pagamentos_consulta on public.oricstudio_pagamentos
for select to authenticated using (
  public.oricstudio_eh_admin() or exists(
    select 1 from public.clinica_usuarios cu
    where cu.clinica_id=oricstudio_pagamentos.clinica_id and cu.user_id=(select auth.uid())
    and cu.ativo=true and cu.papel in ('responsavel','admin_clinica','rt')
  )
);
-- Apenas a função de conciliação privilegiada pode registrar um pagamento.
revoke all on sequence public.oricstudio_pagamentos_id_seq from public,anon,authenticated;

create or replace function public.oricstudio_confirmar_pagamento(
  p_solicitacao_id uuid,p_mp_pagamento_id text,p_mp_assinatura_id text,p_aprovado_em timestamptz
)
returns boolean
language plpgsql security definer set search_path=''
as $$
declare
  p public.oricstudio_solicitacoes;
  v_expira timestamptz;
  v_ins bigint;
  v_now timestamptz := now();
begin
  if auth.role() <> 'service_role' then raise exception 'Apenas conciliação de pagamentos'; end if;
  if p_mp_pagamento_id !~ '^[0-9]+$' or length(p_mp_assinatura_id)<8
     or p_aprovado_em is null or p_aprovado_em > v_now + interval '1 hour' then
    raise exception 'Pagamento inválido';
  end if;
  select * into p from public.oricstudio_solicitacoes
    where id=p_solicitacao_id for update;
  if not found then raise exception 'Solicitação desconhecida'; end if;
  if p.mp_assinatura_id is distinct from p_mp_assinatura_id or
     p.status not in ('pagamento_pendente','pago') then
    raise exception 'Assinatura não confere com solicitação';
  end if;
  insert into public.oricstudio_pagamentos (
    solicitacao_id,clinica_id,mp_pagamento_id,mp_assinatura_id,valor_centavos,aprovado_em
  ) values (
    p.id,p.clinica_id,p_mp_pagamento_id,p_mp_assinatura_id,p.valor_mensal_centavos,p_aprovado_em
  ) on conflict (mp_pagamento_id) do nothing returning id into v_ins;
  if v_ins is null then return false; end if;
  -- Renovação de período ocorre apenas em pagamento aprovado e confirmado pelo MP.
  select greatest(coalesce(l.expira_em,p_aprovado_em),p_aprovado_em) + interval '1 month'
    into v_expira from public.oricstudio_licencas l where l.clinica_id=p.clinica_id;
  if v_expira is null then v_expira := p_aprovado_em + interval '1 month'; end if;
  insert into public.oricstudio_licencas (
    clinica_id,status,quantidade_contas_contratadas,expira_em,motivo
  ) values (
    p.clinica_id,'ativo',p.quantidade_contas,v_expira,
    'Pagamento confirmado via Mercado Pago (OricStúdio)'
  ) on conflict (clinica_id) do update set
    status='ativo',quantidade_contas_contratadas=excluded.quantidade_contas_contratadas,
    expira_em=excluded.expira_em,motivo=excluded.motivo;
  update public.oricstudio_solicitacoes set status='pago',
    provedor='mercadopago',referencia_pagamento=p_mp_pagamento_id,
    mp_assinatura_status='authorized',pagamento_confirmado_em=p_aprovado_em,
    atualizado_em=v_now
  where id=p.id;
  return true;
end;
$$;
revoke all on function public.oricstudio_confirmar_pagamento(uuid,text,text,timestamptz)
from public,anon,authenticated;
grant execute on function public.oricstudio_confirmar_pagamento(uuid,text,text,timestamptz)
to service_role;

comment on function public.oricstudio_confirmar_pagamento(uuid,text,text,timestamptz)
is 'Uso exclusivo após consulta autenticada ao Mercado Pago e verificação de status=approved, BRL, valor e assinatura correta.';
